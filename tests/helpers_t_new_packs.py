"""Subject packs of the T-B generators (tests/test_t_new_classes.py): hand-written Russian content, data only.

A pack is ONE subject with the pieces a situation generator needs. Nothing here is an expected answer of the product: the
cloud is a fake and these sentences are what a fake cloud says. The generators combine the pieces (restriction kind, delivery
shape, user behaviour, timing ...) so that the scenarios differ in structure, not only in words.

Groups (V3 section 10: holdout grouped by whole dialogues / subjects):
  ``dev``      the subjects the tests were written and debugged on;
  ``holdout``  subjects that were never used while writing or debugging a test. Their scenarios sit behind the pytest
               marker ``holdout`` (skipped by default, ``-m holdout`` runs them) and their results were not looked at while
               tests were changed.

Fields (all complete Russian text):
  question   a definition-style question that needs no source lookup (the direct route), ends with «?»
  head       the main clause of a claim, no restriction in it, no final punctuation
  neg / exc / cond   the restriction that makes the claim true: «, но не …» / «, кроме …» / «, только если …»
  tail       a neutral sentence that follows (final punctuation included)
  roles      (base, swapped, inplace): one clause with two roles; the same roles swapped (different lemma order); the same
             roles swapped ONLY by case endings, word order kept (None when the nouns have no distinct nominative/accusative)
  qty        (template with {n}, right number, wrong number)
  hard       a short statement of heavy words, dates or terms (final punctuation included)
  compound   (question with three asks, s1, s2, s3, correction, fixed s1): the correction is a form the classifier recognises
  rewrite    (early prefix, final text): the final text does NOT start with the prefix and flips what the prefix said
  topic      (nominative, accusative, prepositional WITH its preposition: «о механике», «об истории») of the subject name
"""
from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class Pack:
    key: str
    group: str
    subject: str
    question: str
    head: str
    neg: str
    exc: str
    cond: str
    tail: str
    roles: tuple
    qty: tuple
    hard: str
    compound: tuple
    rewrite: tuple
    topic: tuple

    def claim(self, kind):
        """The head with its restriction (``neg`` / ``exc`` / ``cond``), as one sentence."""
        return self.head + getattr(self, kind) + '.'


