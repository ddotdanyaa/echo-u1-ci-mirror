"""The table of tests/test_r21_first_portion.py: R21 (first a short, right gist), one row per question and answer.

A row: ``cls``, the ``question``, the ``answer`` text as the producer streams it, ``ideal`` (the first portion as a person would cut it
by hand, written from the text, never taken from the code), ``want`` (what the first portion MUST hold: the fragments of the answer that
are the gist: the year with its word, the number with its unit, the negation, the condition), ``bad`` (first portions that are not
allowed: the question read back, a bare «Да.», a date without its year, a unit left for the next portion), and ``silent`` (the answer is
nothing but scaffolding: no first portion is the right result).

``want`` and ``bad`` are strings of items separated by « | ». An item of ``want`` is a fragment (ё = е, case ignored) that has to stand in
the first portion. An item of ``bad`` is a whole first portion (compared without the marks at its ends), or a regular expression when
it starts with «~». The oracle (``violations``) is the same for the ideal portion and for the one the code gives: a table that its own
ideal portions do not pass proves nothing (tests/test_r21_first_portion.py::test_the_table_agrees_with_itself).
"""
from __future__ import annotations

import re
from dataclasses import dataclass

import pymorphy3

from helpers_r21_first import normal, words

MORPH = pymorphy3.MorphAnalyzer()


@dataclass(frozen=True)
class Row:
    cls: str
    question: str
    answer: str
    ideal: str
    want: tuple
    bad: tuple
    silent: bool = False

    @property
    def id(self):
        return f'{self.cls}-{ROWS.index(self) + 1:03d}'


ROWS: list = []


def _items(value):
    return tuple(item.strip() for item in str(value or '').split(' | ') if item.strip())


def R(cls, question, answer, ideal, want='', bad='', *, silent=False):
    ROWS.append(Row(cls, question, answer, ideal, _items(want), _items(bad), silent))


# Latin function words: a first portion never ends on one (the Russian ones are tagged by pymorphy3).
LATIN_FUNCTION = frozenset('a an the of in on at by for with without from to into onto about as is are was were be been and or but nor not no if '
                           'that than then so such this these those it its their his her our your my'.split())


def dangling(cue, whole):
    """True when ``cue`` ends on a word that needs the next one (independent of echo_sync: pymorphy3 directly). A mark after the word frees it."""
    if re.search(r'[,;:.!?…—–]\s*$', cue) or not words(cue):
        return False
    last = words(cue)[-1].casefold().replace('ё', 'е')
    if last in LATIN_FUNCTION:
        return True
    parses = MORPH.parse(last)
    if any(p.tag.POS in ('PREP', 'CONJ') for p in parses[:2]) or last in ('не', 'ни', 'бы', 'очень', 'почти', 'более', 'менее', 'самый', 'этот', 'такой'):
        return True
    rest = whole[len(cue):].split()
    if not rest:
        return False
    following = MORPH.parse(re.sub(r'\W', '', rest[0]).casefold())
    for mine in parses[:2]:
        if mine.tag.POS in ('ADJF', 'PRTF'):
            for other in following[:3]:
                if other.tag.POS in ('NOUN', 'ADJF', 'PRTF') and mine.tag.case == other.tag.case and mine.tag.number == other.tag.number:
                    return True
    return False


def violations(row, cue, whole):
    """The reasons ``cue`` is not a right first portion of ``whole`` for ``row`` ([] when it is)."""
    if cue is None:
        return [] if row.silent else ['no first portion']
    if row.silent:
        return ['a first portion of an answer that is only scaffolding']
    out = []
    n = normal(cue)
    if not whole.startswith(cue) or (cue[-1:].isalnum() and whole[len(cue):][:1].isalnum()):
        out.append('not the start of the answer at a word')
    for item in row.want:
        if normal(item) not in n:
            out.append(f'missing «{item}»')
    for item in row.bad:
        if (re.search(item[1:], cue, re.I) if item.startswith('~') else normal(item) == n):
            out.append(f'forbidden «{item}»')
    if len(words(cue)) > 12:
        out.append('longer than 12 words')
    if dangling(cue, whole):
        out.append('ends on a word that needs the next one')
    return out


