def state(chunks, index):
    return {'chunks': list(chunks), 'chunk_index': index, 'completed': False, 'pending_turn': None, 'revision': 1}


def verdict(heard, portion):
    return analyze(heard, state([portion, 'Следующая порция.'], 0), [], CALL)


