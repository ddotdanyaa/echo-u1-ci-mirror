"""F1 (wave F): confirming a meaning-sized portion.

A portion of five words or more is repeated the way a person repeats it: a non-key word may be dropped or changed - a particle, a
conjunction, a manner adverb such as «традиционно» - and the repeat confirms it. An adjective is never dropped (candidate 8 audit, ruling A:
it is a part of the term - «Чистая прибыль», «Номинальная процентная ставка»). Every number, negation, content
noun and verb, preposition and pronoun has to be there; the R2a negative pairs (another number, negation, subject, time, condition) are
never accepted. A repeat that starts with the end of the portion just confirmed and goes on with the waiting one confirms the waiting
one (the owner's «централизованно по плану» while «по плану,» waited, call of 3 Nov 09:55, 324.1 s).

Every pair below is written by hand from the meaning portions of the call's answers and of new answers; the verdicts are the brief's.
"""
