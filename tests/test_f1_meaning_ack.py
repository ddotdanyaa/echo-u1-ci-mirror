def test_there_are_enough_pairs():
    assert len(POSITIVE) >= 20 and len(NEGATIVE) >= 20


@pytest.mark.parametrize('portion,heard', POSITIVE)
def test_a_natural_repeat_of_a_long_portion_confirms_it(portion, heard):
    result = verdict(heard, portion)
    assert result.kind == ACK, (heard, portion, result)


@pytest.mark.parametrize('portion,heard', NEGATIVE)
def test_another_number_negation_subject_time_or_condition_never_confirms(portion, heard):
    result = verdict(heard, portion)
    assert result.kind != ACK, (heard, portion, result)


@pytest.mark.parametrize('portion,heard', [
    ('традиционно относят', 'относят'),                      # the call's own short portions stay strict: an attempt, not a repeat
    ('в первой части', 'в части'),
    ('по плану,', 'по плану рынком'),
    ('почти нет атмосферы', 'нет атмосферы'),
])
def test_a_short_portion_is_still_confirmed_only_word_for_word(portion, heard):
    assert verdict(heard, portion).kind != ACK


# --- the end of the confirmed portion, then the waiting one -----------------------------------------------------------------------------

CALL_CHUNKS = ['Сейчас коротко сформулирую.', 'В том, что ресурсы', 'и производство', 'распределяются', 'централизованно',
               'по плану,', 'а не рынком.']
BATTLE = ['Куликовскую битву обычно датируют', '1380 годом,', 'когда Дмитрий Донской разбил войско Мамая.']


@pytest.mark.parametrize('chunks,index,heard', [
    (CALL_CHUNKS, 5, 'централизованно по плану'),              # the owner's words at 324.1 s
    (CALL_CHUNKS, 5, 'распределяются централизованно по плану'),   # more than the confirmed portion: still its end
    (BATTLE, 1, 'обычно датируют 1380 годом'),
    (BATTLE, 1, 'датируют 1380 годом'),
    (BATTLE, 2, 'годом когда Дмитрий Донской разбил войско Мамая'),
])
def test_a_repeat_that_starts_with_the_confirmed_end_confirms_the_waiting_portion(chunks, index, heard):
    result = analyze(heard, state(chunks, index), [], CALL)
    assert result.kind == ACK, (heard, result)


@pytest.mark.parametrize('chunks,index,heard', [
    (CALL_CHUNKS, 5, 'централизованно по рынку'),                 # the waiting portion itself is wrong
    (CALL_CHUNKS, 5, 'не по плану'),                              # «не» is no end of the confirmed portion
    (CALL_CHUNKS, 4, 'распределяются по плану'),                  # skips the waiting portion
    (BATTLE, 1, 'обычно датируют 1389 годом'),                    # another number
    (BATTLE, 1, 'датируют'),                                       # only the confirmed end
    (CALL_CHUNKS, 1, 'сформулирую в том что ресурсы рынком'),     # the waiting portion plus a foreign word
])
def test_the_overlap_never_confirms_a_wrong_or_missing_waiting_portion(chunks, index, heard):
    assert analyze(heard, state(chunks, index), [], CALL).kind != ACK
