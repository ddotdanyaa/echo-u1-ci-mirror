@pytest.mark.parametrize('text', ['Можешь сказать, что такое налог', 'Можешь объяснить, что значит энтропия', 'Можно рассказать, что означает это слово',
                                  'Можете пояснить что такое инерция', 'Не могли бы вы сказать, что такое налог'])
def test_the_what_of_a_definition_question_is_the_question_word_not_the_conjunction(text):
    """My reading of (b): «что такое / что значит / что означает» after a request verb cannot be the conjunction, so a request stays a request."""
    assert modal_that_index(w(text)) is None, text
    assert modal_request(w(text)), text
