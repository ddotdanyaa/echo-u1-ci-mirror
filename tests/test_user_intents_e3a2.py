@pytest.mark.parametrize('text,at', [
    ('Можно сказать, что он прав', 2), ('Можешь сказать что угодно', 2), ('Можно ли сказать, что он прав', 3),
    ('Не могли бы вы сказать что это', 5), ('Можно мне объяснить, что он прав', 3), ('Можете пожалуйста рассказать, что случилось', 3),
    ('Можно сказать, что он прав, потому что все факты это подтверждают и многое другое', 2),       # no bound of length: it is a statement however long
])
def test_a_request_verb_followed_by_that_is_a_statement_and_its_that_is_a_conjunction(text, at):
    assert modal_that_index(w(text)) == at, text
    assert not modal_request(w(text)), text


