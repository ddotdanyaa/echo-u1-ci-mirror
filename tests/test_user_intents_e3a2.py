def test_a_request_is_at_most_ten_words():
    assert modal_request(w('Можешь объяснить мне разницу между весом и массой простыми словами'))
    assert not modal_request(w('Можешь объяснить мне разницу между весом и массой простыми словами пожалуйста'))
    assert not modal_request(w('Можешь объяснить это нам всем очень подробно и по шагам с примерами'))


