# -- ruling 5 (DEF-T-06): a modal word asks only as a request ------------------------------------------------------------------------

# Fix round 1 (coordinator, binding): recall beats precision for requests. The modals of permission and ability (можно, можешь, можете, могли бы, мог бы,
# не могли бы, не мог бы) ask as a request when a request verb or a request word follows. Fix round 2: the obligation modals (нужно, надо, нужен, нужна, стоит,
# следует, необходимо) ask as a request only when a request OBJECT word follows them directly (подробнее, пример, ещё, проще, уточнить …) and at most two more
# words; «Нужно остановить платёж по счёту» / «Надо повторить опыт через неделю» stay statements. «верно» / «правда» ask only with «?» or «ли».

def test_the_closed_list_of_modal_words():
    assert MODAL_WORDS == {'нужно', 'можно', 'надо', 'верно', 'правда', 'можешь', 'можете', 'стоит', 'следует', 'необходимо', 'нужен', 'нужна', 'нужны'}
    assert OBLIGATION_WORDS == {'нужно', 'надо', 'нужен', 'нужна', 'нужны', 'стоит', 'следует', 'необходимо'}


