"""R07 (stall and tail): runs the whole table through the production functions and writes the results.

    python tools/r07_tail_table.py --json out.json            # what the code in this tree does, row by row
    python tools/r07_tail_table.py --report base.json p1.json p2.json ... --csv table.csv --known tests/r07_known.py

The first form calls ``ControlledMedia._said_of`` / ``_started`` / ``_tail_repeated`` / ``_aligned_head`` for every row of ``tests/helpers_r07_tail*`` and
dumps the verdicts. The second form takes the dump of the tree as it is (``base``) and the dumps of the same tree after each proposed patch step
(``p1`` is patch 1, ``p2`` patch 1+2, ...): a row that is wrong in ``base`` is filed under the first step after which it is right (``F1``...), or ``OPEN``
(no proposed step fixes it), and the CSV and the ``tests/r07_known.py`` that holds the expected failures are written. Nothing is run against a model,
a phone or the network; the cwd must hold ``echo_sync`` (the tree under test).
"""
from __future__ import annotations

import argparse
import csv
import json
import sys
import tempfile
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'tests'))
sys.path.insert(0, str(Path.cwd()))


def evaluate():
    import helpers_r07_tail as T
    import helpers_r07_tails as U
    controller = U.make_controller(tempfile.mkdtemp())
    out = []
    for row in T.all_rows():
        for route in U.ROUTES:
            verdict, cue = U.cue_verdict(controller, row, route)
            out.append({'id': f'{row.id}@{route}', 'table': 'cue', 'cat': row.cat, 'route': route, 'portion': row.portion, 'said': row.said,
                        'expect': row.portion if row.expect is None else row.expect, 'cue': cue, 'verdict': verdict, 'note': row.note})
    for row in list(U.confirm_rows()) + list(U.confirm_hand_rows()):
        got = U.is_confirmed(controller, row)
        out.append({'id': row.id, 'table': 'confirm', 'cat': 'confirm', 'route': '-', 'portion': row.portion, 'said': row.said,
                    'expect': 'confirmed' if row.confirmed else 'not confirmed', 'cue': 'confirmed' if got else 'not confirmed',
                    'verdict': 'OK' if got == row.confirmed else ('FALSE_ACCEPT' if got else 'FALSE_REFUSAL'), 'note': f'tail «{row.tail}»; {row.note}'})
    for row in U.aligned_rows():
        got = U.head_of(controller, row)
        out.append({'id': row.id, 'table': 'aligned', 'cat': 'aligned', 'route': '-', 'portion': row.portion, 'said': row.said,
                    'expect': row.head or 'no head', 'cue': got or 'no head',
                    'verdict': 'OK' if got == row.head else ('FALSE_SPLIT' if got else 'MISSED_SPLIT'), 'note': row.note})
    return out


def summary(rows):
    count = Counter((row['table'], row['cat'], row['route'], row['verdict']) for row in rows)
    lines = []
    for table, cat, route in sorted({key[:3] for key in count}):
        parts = {key[3]: n for key, n in count.items() if key[:3] == (table, cat, route)}
        lines.append(f'{table:8} {cat:16} {route:6} ' + ' '.join(f'{v}={n}' for v, n in sorted(parts.items())))
    total = Counter(row['verdict'] for row in rows)
    lines.append('TOTAL ' + ' '.join(f'{v}={n}' for v, n in sorted(total.items())) + f'  rows={len(rows)}')
    return lines


def report(paths, csv_path, known_path):
    base, *steps = [{row['id']: row for row in json.loads(Path(p).read_text(encoding='utf-8'))} for p in paths]
    known, lines = {}, []
    for rid, row in base.items():
        fixed = ''
        if row['verdict'] != 'OK':
            fixed = next((f'F{index + 1}' for index, step in enumerate(steps) if step[rid]['verdict'] == 'OK'), 'OPEN')
            known[rid] = fixed
        lines.append({**row, 'fixed_by': fixed, **{f'after_p{index + 1}': step[rid]['verdict'] for index, step in enumerate(steps)}})
    if csv_path:
        with open(csv_path, 'w', encoding='utf-8', newline='') as handle:
            writer = csv.DictWriter(handle, fieldnames=list(lines[0]), delimiter=';')
            writer.writeheader()
            writer.writerows(lines)
    if known_path:
        body = ['"""Rows of the R07 table that the production code gets wrong, and the proposed patch step that fixes each (generated by tools/r07_tail_table.py --report).',
                '',
                'F1.. is the step of ``cloud_context/reports/r07-tail.md`` after which the row is right; OPEN: no proposed step fixes it. A test of a row listed here is',
                '``xfail(strict=True)``: when the patch lands the row turns right and the strict xfail fails, so the entry has to be deleted with it."""',
                'KNOWN = {']
        body += [f'    {rid!r}: {code!r},' for rid, code in sorted(known.items())]
        body.append('}')
        Path(known_path).write_text('\n'.join(body) + '\n', encoding='utf-8')
    return Counter(known.values())


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--json')
    parser.add_argument('--report', nargs='+')
    parser.add_argument('--csv')
    parser.add_argument('--known')
    args = parser.parse_args()
    if args.json:
        rows = evaluate()
        Path(args.json).write_text(json.dumps(rows, ensure_ascii=False), encoding='utf-8')
        print('\n'.join(summary(rows)))
    if args.report:
        print(dict(report(args.report, args.csv, args.known)))


if __name__ == '__main__':
    main()
