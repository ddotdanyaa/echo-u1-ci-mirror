def check():
    """Problems of the map against the tools: [] when sound."""
    from tools.rehearsal import plan as P
    from tools.replay import chaos
    from tools.ladder import scenes as L
    problems, ids = [], set()
    for sid, name, classes, measure in STAGES:
        if sid in ids:
            problems.append(f'{sid} twice')
        ids.add(sid)
        if len(classes) < 5:
            problems.append(f'{sid} {name}: {len(classes)} classes, 5 needed')
        if not measure:
            problems.append(f'{sid}: no measure')
        for cls, scene in classes:
            kind, _, arg = scene.partition(':')
            if kind == 'chaos' and arg not in chaos.FAULTS:
                problems.append(f'{sid} {cls}: no fault {arg}')
            elif kind == 'rehearsal' and arg not in P.PLAN:
                problems.append(f'{sid} {cls}: no rehearsal {arg}')
            elif kind == 'ladder' and arg not in L.LEVELS:
                problems.append(f'{sid} {cls}: no level {arg}')
            elif kind == 'fuzz' and not re.fullmatch(r'A\d[eo]?', arg):
                problems.append(f'{sid} {cls}: no invariant {arg}')
            elif kind == 'half_hour' and arg not in ('unanswered', 'extra', 'stuck', 'skipped'):
                problems.append(f'{sid} {cls}: no counter {arg}')
            elif kind == 'marathon' and arg not in ('answered', 'order', 'clean', 'growth', 'stuck', 'lost'):
                problems.append(f'{sid} {cls}: no counter {arg}')
            elif kind not in ('chaos', 'rehearsal', 'ladder', 'fuzz', 'half_hour', 'marathon', 'blind'):
                problems.append(f'{sid} {cls}: scene {scene}')
    return problems


def counts():
    classes = [c for _, _, cs, _ in STAGES for c in cs]
    return {'stages': len(STAGES), 'classes': len(classes), 'blind': sum(1 for _, s in classes if s == 'blind')}


if __name__ == '__main__':
    bad = check()
    print(counts())
    print('\n'.join(bad) or 'the map is sound')
    sys.exit(1 if bad else 0)
